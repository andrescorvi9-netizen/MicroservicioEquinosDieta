-- Esquema caballos: propiedad exclusiva del microservicio registro-caballo
CREATE SCHEMA IF NOT EXISTS caballos;

CREATE TABLE caballos.caballo (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     bigint       NOT NULL, -- referencia lógica a auth.usuario (sin clave foránea entre esquemas)
    nombre         varchar(120) NOT NULL,
    codigo         varchar(40)  NOT NULL,
    peso_kg        numeric(7,2) NOT NULL,
    categoria      varchar(20)  NOT NULL,
    estado_salud   varchar(30)  NOT NULL,
    activo         boolean      NOT NULL DEFAULT true,
    creado_en      timestamptz  NOT NULL DEFAULT now(),
    actualizado_en timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_caballo_peso CHECK (peso_kg > 0),
    CONSTRAINT ck_caballo_categoria CHECK (categoria IN ('potrillo', 'joven', 'adulto')),
    CONSTRAINT ck_caballo_estado_salud CHECK (estado_salud IN
        ('sin_complicaciones', 'deshidratacion', 'desnutricion', 'laminitis', 'colicos'))
);

-- El código es único solo entre caballos activos: un caballo borrado (activo = false) libera su código
CREATE UNIQUE INDEX ux_caballo_codigo_activo ON caballos.caballo (codigo) WHERE activo;

CREATE INDEX ix_caballo_usuario ON caballos.caballo (usuario_id);
