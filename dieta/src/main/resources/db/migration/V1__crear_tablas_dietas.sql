-- Esquema dietas: propiedad exclusiva del microservicio dieta
CREATE SCHEMA IF NOT EXISTS dietas;

-- Catálogo: 3 categorías
CREATE TABLE dietas.categoria (
    codigo      varchar(20)  PRIMARY KEY,
    nombre      varchar(120) NOT NULL,
    descripcion text         NOT NULL,
    notas_nrc   text         NOT NULL
);

-- Catálogo: 5 estados de salud
CREATE TABLE dietas.estado_salud (
    codigo varchar(30)  PRIMARY KEY,
    nombre varchar(120) NOT NULL
);

-- Catálogo: 15 perfiles (3 categorías x 5 estados)
CREATE TABLE dietas.perfil_dieta (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_codigo     varchar(20)  NOT NULL REFERENCES dietas.categoria (codigo),
    estado_codigo        varchar(30)  NOT NULL REFERENCES dietas.estado_salud (codigo),
    fuente               varchar(20)  NOT NULL,
    criterio_nutricional text         NOT NULL,
    peso_ref_kg          numeric(7,2) NOT NULL,
    ed_mcal_dia          numeric(7,2) NOT NULL,
    pc_g_dia             numeric(8,2) NOT NULL,
    ca_g_dia             numeric(7,2) NOT NULL,
    p_g_dia              numeric(7,2) NOT NULL,
    pct_ms_peso          numeric(4,1) NOT NULL,
    pct_forraje          numeric(5,2) NOT NULL,
    pct_concentrado      numeric(5,2) NOT NULL,
    manejo_agua          text         NOT NULL,
    CONSTRAINT uq_perfil_categoria_estado UNIQUE (categoria_codigo, estado_codigo),
    CONSTRAINT ck_perfil_fuente CHECK (fuente IN ('documentado', 'inferido')),
    CONSTRAINT ck_perfil_reparto CHECK (pct_forraje + pct_concentrado = 100)
);

-- Catálogo: listas de cada perfil (forrajes, concentrados, suplementos, reglas, advertencias)
CREATE TABLE dietas.perfil_dieta_item (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id bigint      NOT NULL REFERENCES dietas.perfil_dieta (id) ON DELETE CASCADE,
    tipo      varchar(30) NOT NULL,
    orden     integer     NOT NULL,
    texto     text        NOT NULL,
    CONSTRAINT ck_item_tipo CHECK (tipo IN ('forraje_base', 'forraje_evitar', 'concentrado_recomendado',
        'concentrado_evitar', 'suplemento', 'regla_alimentacion', 'advertencia'))
);

CREATE INDEX ix_item_perfil ON dietas.perfil_dieta_item (perfil_id);

-- Dietas generadas. Guardan copia de categoría, estado y peso del caballo en el momento de generarse.
CREATE TABLE dietas.dieta (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     bigint       NOT NULL, -- referencia lógica a auth.usuario
    caballo_id     bigint       NOT NULL, -- referencia lógica a caballos.caballo
    caballo_nombre varchar(120) NOT NULL, -- copia del caballo al generar la dieta
    caballo_codigo varchar(40)  NOT NULL, -- copia del caballo al generar la dieta
    perfil_id      bigint       NOT NULL REFERENCES dietas.perfil_dieta (id),
    categoria      varchar(20)  NOT NULL,
    estado_salud   varchar(30)  NOT NULL,
    peso_kg        numeric(7,2) NOT NULL,
    ms_total_kg    numeric(7,2) NOT NULL,
    forraje_kg     numeric(7,2) NOT NULL,
    concentrado_kg numeric(7,2) NOT NULL,
    observaciones  text,
    creado_en      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_dieta_peso CHECK (peso_kg > 0)
);

-- Historial y dieta vigente de un caballo
CREATE INDEX ix_dieta_caballo_fecha ON dietas.dieta (caballo_id, creado_en DESC);

CREATE INDEX ix_dieta_usuario ON dietas.dieta (usuario_id);
